export type Language = keyof typeof translations
export type Translation = {
  [K in keyof typeof translations.en]: string
}

export function resolveTranslation(
  selected: Record<string, string>,
  fallback: Record<string, string>,
  key: string,
): string {
  const localized = selected[key]
  if (typeof localized === 'string' && localized.length > 0) return localized
  const english = fallback[key]
  return typeof english === 'string' ? english : key
}

export function translationFor(language: Language, key: string): string {
  return resolveTranslation(
    translations[language] as Record<string, string>,
    translations.en as Record<string, string>,
    key,
  )
}

export function getTranslationCatalog(language: Language): Translation {
  return new Proxy(translations[language] as Translation, {
    get(target, property, receiver) {
      if (typeof property === 'string') {
        return translationFor(language, property)
      }
      return Reflect.get(target, property, receiver)
    },
  })
}

export function getInitialLanguage(
  storage?: Pick<Storage, 'getItem'>,
): Language {
  try {
    const preference = storage
      ? storage.getItem('therasim-language')
      : window.localStorage.getItem('therasim-language')
    return preference === 'fa' ? 'fa' : 'en'
  } catch {
    return 'en'
  }
}

export function persistLanguage(
  language: Language,
  storage?: Pick<Storage, 'setItem'>,
): void {
  try {
    if (storage) storage.setItem('therasim-language', language)
    else window.localStorage.setItem('therasim-language', language)
  } catch {
    // The interface remains usable when browser storage is unavailable.
  }
}
